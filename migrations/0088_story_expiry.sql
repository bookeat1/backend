-- У сторис появляется СРОК ЖИЗНИ — момент, после которого гость её больше не
-- видит.
--
-- ЧТО БЫЛО. В 0065 у `restaurant_stories` единственный рубильник видимости —
-- `is_active`. Он ручной: заведение выкладывает «сегодня свежие устрицы»,
-- забывает выключить, и гость неделю смотрит на позавчерашних устриц. Никакого
-- автоматического «протухания» у карточки не было.
--
-- ЧТО ДЕЛАЕТ. Добавляет ОДНУ nullable-колонку `expires_at` — абсолютный момент
-- («показывать до»). Правило чтения: сторис видна гостю, если
-- `is_active AND (expires_at IS NULL OR expires_at > now)`.
--
-- NULL — ЭТО НЕ «ПРОСРОЧЕНО», А «БЕССРОЧНО». Это главное свойство миграции:
-- у ВСЕХ существующих строк после наката `expires_at IS NULL`, и предикат выше
-- пропускает их без изменений. Ни одна выложенная сторис не исчезнет в момент
-- деплоя. Срок — ОПЦИОНАЛЬНЫЙ по решению владельца продукта; кабинет лишь
-- ПРЕДЛАГАЕТ по умолчанию +24 часа, а заведение вправе очистить поле.
--
-- ПОЧЕМУ timestamptz, А НЕ «дата + таймзона заведения». Это МОМЕНТ времени, а
-- не настенное время: «устрицы протухают завтра в 12:00 по местному» — это одна
-- точка на мировой оси, а не правило, которое надо каждый день пересчитывать в
-- зоне заведения. Так же устроены `events.starts_at/ends_at` и
-- `otp_codes.expires_at`: timestamptz + сравнение с моментом «сейчас».
-- `restaurants.timezone` (см. domain/venue_timezone.go) нужен там, где смысл
-- имеет именно КАЛЕНДАРНЫЙ ДЕНЬ или часы работы — выплаты, расписание,
-- уведомления. Здесь такой привязки нет, и заводить вторую конвенцию ради
-- одной колонки было бы хуже, чем следовать существующей.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Нет CHECK «`expires_at` в будущем»: во-первых, такой CHECK
-- нарушается сам собой со временем (строка, валидная при вставке, завтра
-- становится невалидной, и любой UPDATE по ней падает); во-вторых, прошедшая
-- дата — это законный способ «спрятать прямо сейчас» и обязательное состояние
-- для сценария «продлить просроченную сторис» в кабинете.
--
-- Нет и фонового воркера, который вычищал бы протухшее: фильтр в SELECT даёт
-- тот же результат без ещё одного процесса, который может отстать или упасть, и
-- сохраняет строку — просроченную сторис заведение продлевает или удаляет само.
--
-- НОМЕР. Прод на 87, максимальный файл в `migrations/` — 0087, свободный
-- следующий — 0088.
--
-- ИНДЕКС. Отдельный индекс не заводится намеренно.
-- `idx_restaurant_stories_listing (restaurant_id, is_active, sort_order,
-- created_at, id)` из 0065 продолжает и отбирать строки, и давать порядок; новый
-- предикат по `expires_at` — дешёвая доперепроверка на считанных строках, потому
-- что у одного заведения сторис единицы, а не тысячи. Добавление `expires_at` в
-- этот индекс сломало бы index-ordered scan (колонка встала бы перед ключами
-- сортировки), а частичный индекс по `expires_at > now()` невозможен: `now()`
-- не IMMUTABLE.
--
-- БЛОКИРОВКИ. Nullable-колонка без DEFAULT существующие строки не переписывает —
-- это правка каталога, лочащая таблицу на доли секунды.

SET lock_timeout = '3s';

ALTER TABLE restaurant_stories
    ADD COLUMN expires_at timestamptz;

COMMENT ON COLUMN restaurant_stories.expires_at IS
    'Момент, после которого сторис перестаёт показываться гостю. NULL = '
        'бессрочно (все строки, созданные до миграции 0088). Гостю видно, '
        'когда is_active AND (expires_at IS NULL OR expires_at > now()); в '
        'кабинете заведения просроченная сторис остаётся видимой с пометкой, '
        'чтобы её можно было продлить или удалить.';

