--
-- ЗАЧЕМ. Подвал сайта ссылается на «Как это работает», «Отмена брони»,
-- «Оферта», «Политика данных», «Контакты», «Вакансии», «О BookEat» — до этой
-- миграции ни одна из них не существует и ссылка ведёт в никуда. Текст
-- (включая юридические — оферту и политику данных) должен редактироваться
-- суперадминистратором из кабинета, без деплоя и без участия инженера.
-- «Блог» сюда не входит — он ведёт на существующий раздел /articles.
--
-- ПОЧЕМУ ОДНА ТАБЛИЦА С ЗАКРЫТЫМ НАБОРОМ СТРОК, А НЕ CMS. Страниц ровно
-- семь, список не растёт из кабинета (создание новых слагов — вне скоупа,
-- см. спеку), контент — Markdown без версий и черновиков («простая замена
-- контента» — владелец не оспорил это допущение). Ровно тот же выбор уже
-- сделан для mobile_app_policies (0103) и venue_features/cuisines/cities:
-- закрытый справочник — это PRIMARY KEY с CHECK, а не свободные строки в
-- мешке key-value.
--
-- ПОЧЕМУ published_at, А НЕ ПРОСТО title/body. Задача явно требует, чтобы
-- страница без наполненного текста НЕ показывалась гостю как страница с
-- пустым телом (это особенно важно для оферты и политики данных — юр.
-- тексты, для которых «пусто» страшнее, чем «страницы ещё нет»). NULL =
-- черновик (сайт отвечает 404), non-NULL = опубликована. Это НЕ версии и НЕ
-- отдельная таблица черновиков — один флаг на одной живой строке, ровно тот
-- уровень сложности, который спека просила.
--
-- НОМЕР. На 2026-09-06 максимум по всем веткам origin/* — 0104
-- (`0104_locale_comment_ko_zh.sql`); проверено `git ls-tree origin/<branch>
-- migrations/` по каждой ветке. 0105 свободен.

SET lock_timeout = '3s';

CREATE TABLE platform_pages
(
    -- Слаг — он же путь на сайте (book-eat.com/<slug>) и первичный ключ.
    -- varchar + CHECK, а не CREATE TYPE ... AS ENUM (правило схемы,
    -- migrations/embed.go): значения совпадают с domain.PlatformPageSlugs.
    -- Список закрыт: приложение никогда не вставляет и не удаляет строку,
    -- только обновляет одну из семи, засеянных ниже.
    slug         varchar(64) PRIMARY KEY
        CHECK (slug IN ('about', 'jobs', 'contacts', 'how-it-works',
                         'cancellation', 'offer', 'privacy')),

    -- Заголовок и тело. Базовая колонка — русский текст, *_i18n — карта
    -- остальных языков, тот же инвариант, что у каждого `*_i18n` поля в этой
    -- схеме (0101): i18n['ru'] == колонка, инвариант держит usecase
    -- (domain.ApplyTranslations), не CHECK — общая причина расписана в 0101
    -- (проверка на каждой строке упала бы на исторически разошедшихся
    -- строках).
    title        text        NOT NULL,
    title_i18n   jsonb,
    -- Markdown. NOT NULL DEFAULT '' — пустое тело такое же законное
    -- состояние, как «текста ещё нет» (черновик); published_at запрещает
    -- пустому телу попасть к гостю (инвариант держит usecase, см. выше).
    body         text        NOT NULL DEFAULT '',
    body_i18n    jsonb,

    -- Формат тела. Сегодня только markdown; колонка — а не константа в
    -- коде — только чтобы будущий второй формат не требовал новой миграции
    -- ради одной колонки. CHECK держит её единственным известным значением,
    -- пока такого формата нет.
    format       varchar(16) NOT NULL DEFAULT 'markdown'
        CHECK (format = 'markdown'),

    -- NULL = черновик (сайт отвечает 404 гостю), non-NULL = опубликована.
    -- Это ВСЯ состояние-машина: ни отдельной таблицы черновиков, ни версий.
    published_at timestamptz,

    -- Кто сохранял последним. НАМЕРЕННО БЕЗ FK на users. Эта таблица — один
    -- раз засеянный семью строками справочник, который должен пережить весь
    -- тестовый прогон (как mobile_app_policies/cities/cuisines); почти
    -- каждый интеграционный тест в проекте делает `testdb.Truncate(...,
    -- "users")`, а `TRUNCATE ... CASCADE` обнуляет ЛЮБУЮ таблицу, у которой
    -- есть FK на усекаемую, — по ON DELETE SET NULL это НЕ смотрит вообще,
    -- CASCADE у TRUNCATE игнорирует его и просто чистит зависимую таблицу
    -- целиком. С реальным FK семь строк здесь гарантированно исчезали бы
    -- посреди `go test -p1 ./...` от чужого, никак не связанного теста —
    -- ровно тот класс граблей, что уже описан для payment_providers
    -- (conventions/bookeat-backend.md, «TEST-DB POLLUTION TRAP»). Значение —
    -- просто атрибуция «кто правил последним»; ссылочная целостность здесь
    -- не критична настолько, чтобы платить такую цену.
    updated_by   uuid,

    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE platform_pages IS
    'Семь редактируемых текстовых страниц подвала сайта (spec T4). Набор строк '
        'закрыт (CHECK на slug), создаётся и живёт только этой миграцией.';
COMMENT ON COLUMN platform_pages.published_at IS
    'NULL = черновик, сайт отвечает 404. Non-NULL = опубликована, гость видит '
        'body как оно есть прямо сейчас — без версий и без задержки.';
COMMENT ON COLUMN platform_pages.title_i18n IS
    'Переводы заголовка: {"kk": …, "en": …}. Ключ ''ru'' равен колонке title '
        '(инвариант держит usecase/platformpages). NULL = переводов нет.';
COMMENT ON COLUMN platform_pages.body_i18n IS
    'Переводы Markdown-тела. Ключ ''ru'' равен колонке body. NULL = переводов нет, '
        'гость на непереведённом языке видит русский текст.';

-- Засев: семь строк с русскими заголовками из подвала, ПУСТЫМ телом,
-- published_at = NULL. Реальный текст (включая перенос оферты и политики
-- данных) заполняет владелец через кабинет — разработчики юридический текст
-- не сочиняют (см. спеку, риск №2).
INSERT INTO platform_pages (slug, title)
VALUES ('about', 'О BookEat'),
       ('jobs', 'Вакансии'),
       ('contacts', 'Контакты'),
       ('how-it-works', 'Как это работает'),
       ('cancellation', 'Отмена брони'),
       ('offer', 'Оферта'),
       ('privacy', 'Политика данных')
ON CONFLICT (slug) DO NOTHING;

