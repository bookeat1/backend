-- Симметричный откат: таблица существует только с этой миграции, ничто
-- другое на неё не ссылается (users.id — единственный внешний ключ и смотрит
-- ИЗ неё, не на неё), поэтому DROP безопасен даже на заполненной таблице.
-- Опубликованный текст при откате ТЕРЯЕТСЯ — это осознанно, тот же выбор,
-- что и в 0101/0103: висящая таблица, в которую откатившийся код больше не
-- пишет, но которую следующий накат прочитал бы со вчерашним текстом, хуже,
-- чем честная потеря.
DROP TABLE IF EXISTS platform_pages;
