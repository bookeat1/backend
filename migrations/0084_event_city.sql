-- +goose Up

-- У события появляется СВОЙ город.
--
-- ЧТО БЫЛО. В `events` колонки города нет вообще (0031). Город события
-- существовал только транзитивно, через заведение-хозяина: публичная витрина
-- фильтрует `r.city = $n` ПОСЛЕ `JOIN restaurants r`
-- (internal/infrastructure/postgres/event/repository.go). Следствий два:
--   * событие платформы, у которого заведения нет, выразить нечем;
--   * `?city=` сравнивался со строкой в лоб, мимо справочника 0081, поэтому
--     третий город, заведённый в кабинете, для афиши не работал.
--
-- ЧТО ДЕЛАЕТ ЭТА МИГРАЦИЯ. Добавляет НЕОБЯЗАТЕЛЬНОЕ ПЕРЕОПРЕДЕЛЕНИЕ города на
-- событии — ту же форму, что у подборок гастрогида (0061), плюс связь со
-- справочником и триггер, как у заведений (0081).
--
-- СЕМАНТИКА КОЛОНКИ — ровно три состояния, и это главное решение здесь:
--   city IS NULL  + есть заведение  → город БЕРЁТСЯ У ЗАВЕДЕНИЯ на чтении
--                                     (`COALESCE(e.city, r.city)`). Это
--                                     сегодняшнее поведение, буква в букву.
--   city IS NULL  + заведения нет   → показывать во ВСЕХ городах. Сегодня
--                                     недостижимо (restaurant_id NOT NULL),
--                                     это задел под карточку «Витрина».
--   city = 'Алматы'                 → событие принудительно в этом городе,
--                                     что бы ни говорило заведение.
--
-- ПОЧЕМУ ВЫВОД НА ЧТЕНИИ, А НЕ ТРИГГЕР, КОПИРУЮЩИЙ ГОРОД ЗАВЕДЕНИЯ В СОБЫТИЕ.
-- Копия протухает. Заведение переезжает (или ему правят город в кабинете —
-- PATCH /restaurants/:id это умеет), и все его будущие события остались бы
-- висеть в старом городе до тех пор, пока кто-нибудь их не тронет. Чтобы
-- копия не протухала, пришлось бы вешать ЕЩЁ один триггер на `restaurants`,
-- который каскадом переписывает `events` — то есть один UPDATE заведения
-- превращается в запись по всем его событиям, включая давно прошедшие, ради
-- значения, которое и так однозначно выводится одним COALESCE в том же JOIN,
-- который витрина уже делает. Вывод на чтении не может разъехаться с
-- источником по определению и не требует переноса данных вообще.
--
-- ЧЕГО МИГРАЦИЯ НЕ ДЕЛАЕТ. `events.restaurant_id` остаётся NOT NULL —
-- события без заведения это отдельная карточка («Витрина»). Колонка города
-- спроектирована так, чтобы та работа не была заблокирована: ветка
-- «city IS NULL и заведения нет» уже описана и уже реализована в предикате
-- чтения, там останется снять NOT NULL и заменить JOIN на LEFT JOIN.

SET lock_timeout = '3s';

-- ---------------------------------------------------------------------------
-- Колонки.
--
-- ЧЕСТНО ПРО БЛОКИРОВКИ (0083 обещал «мгновенный» эксклюзив, удерживая
-- ACCESS EXCLUSIVE на постройке индекса — здесь так не делаем):
--
--   * ALTER TABLE ... ADD COLUMN берёт ACCESS EXCLUSIVE на `events` —
--     на это время таблица не читается и не пишется. Обе колонки nullable и
--     БЕЗ DEFAULT, поэтому переписывания строк нет (только правка каталога),
--     это доли миллисекунды независимо от размера таблицы.
--   * Внешний ключ на `cities` добавляется ОТДЕЛЬНЫМ statement'ом как
--     NOT VALID и валидируется следом. Это не украшение: обычный ADD
--     CONSTRAINT ... REFERENCES прогоняет проверочный скан ПОД ACCESS
--     EXCLUSIVE, а NOT VALID + VALIDATE держит эксклюзив только на объявлении,
--     а скан (тривиальный — все значения NULL) делает под SHARE UPDATE
--     EXCLUSIVE, не мешая чтениям и обычным UPDATE.
--   * CREATE INDEX ниже берёт SHARE: чтения проходят, ЗАПИСИ в `events`
--     ждут постройки. CONCURRENTLY здесь невозможен — goose гоняет миграцию
--     в транзакции. На сегодняшнем объёме (события считаются сотнями) это
--     доли секунды; если таблица когда-нибудь вырастет до миллионов строк,
--     этот индекс надо будет строить отдельно и CONCURRENTLY.
--
-- lock_timeout = 3s выше означает: не дождались окна — миграция падает и
-- откатывается целиком, а не встаёт в очередь, подвесив за собой писателей.
-- ---------------------------------------------------------------------------

ALTER TABLE events
    -- Каноническое НАЗВАНИЕ города (та же валюта, что `restaurants.city`), а
    -- не код: витрина сравнивает города строками, и хранить здесь что-то
    -- другое означало бы приводить типы в каждом запросе.
    -- NULL = переопределения нет (см. семантику выше).
    ADD COLUMN city    varchar,
    -- Ссылка на справочник — ровно та же роль, что у restaurants.city_id:
    -- строка это отображение, справочник — источник правды. Нужна для двух
    -- вещей: переименование города находит свои события по ссылке, а не
    -- перебором строк, и неизвестный город остаётся представимым
    -- (city IS NOT NULL + city_id IS NULL = «строку задали, в справочнике
    -- такого нет»).
    ADD COLUMN city_id uuid;

ALTER TABLE events
    ADD CONSTRAINT events_city_id_fkey
        FOREIGN KEY (city_id) REFERENCES cities (id) ON DELETE RESTRICT NOT VALID;
ALTER TABLE events
    VALIDATE CONSTRAINT events_city_id_fkey;

COMMENT ON COLUMN events.city IS
    'Переопределение города. NULL = город берётся у заведения-хозяина '
        '(COALESCE(e.city, r.city)), а у события без заведения NULL означает '
        '«во всех городах».';
COMMENT ON COLUMN events.city_id IS
    'Ссылка на справочник cities для переопределённого города. NULL при '
        'city IS NULL, а также когда написание не нашлось в city_aliases.';

-- Обратное направление: «события этого города». Нужно переименованию города
-- (usecase/cities.Update переписывает строку у привязанных строк в той же
-- транзакции). Частичный — переопределение есть у меньшинства событий, и
-- индексировать NULL-хвост незачем.
CREATE INDEX idx_events_city_id ON events (city_id) WHERE city_id IS NOT NULL;

-- Отдельный индекс под сам фильтр витрины НЕ создаётся, и это осознанно: в
-- предикате стоит COALESCE(e.city, r.city) по двум таблицам — обычным индексом
-- он не покрывается в принципе, а события на платформе считаются сотнями.
-- Тот же выбор сделан для подборок гастрогида в 0061.

-- ---------------------------------------------------------------------------
-- Триггер: строка и ссылка не расходятся, кто бы ни писал.
--
-- Зеркало restaurants_sync_city (0081), но короче — здесь колонка nullable, и
-- «города нет» это законное состояние, а не дыра.
--
-- Правила:
--   пустая/NULL строка  → обе колонки в NULL. «Переопределения нет» имеет
--                         ровно ОДНО представление, иначе '' и NULL начали бы
--                         значить одно и то же по-разному.
--   сменили city_id     → главная ссылка, строка подтягивается за ней. Это
--                         путь прямой привязки к справочнику.
--   иначе               → главная строка: резолвим по синонимам (код
--                         «almaty», историческое «Алма-Ата», любой регистр) и
--                         приводим к каноническому написанию. Без этого
--                         событие, записанное как «Нур-Султан», было бы
--                         привязано к Астане, но не нашлось бы фильтром
--                         «Астана» — витрина сравнивает строки точно.
--                         Ветка срабатывает и на UPDATE без изменений: строка,
--                         чей город завели в справочнике позже, долечивается
--                         на следующей записи (то же самолечение, что в 0081).
-- ---------------------------------------------------------------------------

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION events_sync_city() RETURNS trigger AS
$$
DECLARE
    resolved uuid;
BEGIN
    IF NEW.city IS NULL OR btrim(NEW.city) = '' THEN
        NEW.city := NULL;
        NEW.city_id := NULL;
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE' AND NEW.city_id IS DISTINCT FROM OLD.city_id AND NEW.city_id IS NOT NULL THEN
        SELECT c.name INTO NEW.city FROM cities c WHERE c.id = NEW.city_id;
        RETURN NEW;
    END IF;

    SELECT a.city_id INTO resolved
    FROM city_aliases a
    WHERE a.alias = city_key(NEW.city);
    NEW.city_id := resolved;
    IF resolved IS NOT NULL THEN
        SELECT c.name INTO NEW.city FROM cities c WHERE c.id = resolved;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
-- +goose StatementEnd

CREATE TRIGGER trg_events_sync_city
    BEFORE INSERT OR UPDATE
    ON events
    FOR EACH ROW
EXECUTE FUNCTION events_sync_city();

-- ---------------------------------------------------------------------------
-- ПЕРЕНОС ДАННЫХ: его здесь нет, и это не забывчивость.
--
-- Все существующие события получают city IS NULL, а NULL при заполненном
-- restaurant_id читается как «город заведения» — то есть ровно то, чем город
-- события был до этой миграции. Любой UPDATE существующих строк был бы либо
-- бессмысленным (записать в событие то же, что уже видно через JOIN), либо
-- вредным (заморозить город на момент миграции и разойтись с заведением при
-- первом же переезде). Отсюда же идемпотентность: переносить нечего, повторный
-- прогон Down + Up даёт тот же результат.
-- ---------------------------------------------------------------------------

-- +goose Down

DROP TRIGGER IF EXISTS trg_events_sync_city ON events;
DROP FUNCTION IF EXISTS events_sync_city();
DROP INDEX IF EXISTS idx_events_city_id;
-- Переопределения городов теряются вместе с колонкой — восстанавливать нечего:
-- до 0084 их не существовало, а город событий и после отката продолжает
-- выводиться из заведения-хозяина.
ALTER TABLE events
    DROP CONSTRAINT IF EXISTS events_city_id_fkey,
    DROP COLUMN city_id,
    DROP COLUMN city;
