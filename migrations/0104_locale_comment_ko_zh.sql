-- +goose Up

-- КОРЕЙСКИЙ И КИТАЙСКИЙ СТАЛИ ОБСЛУЖИВАЕМЫМИ ЯЗЫКАМИ.
--
-- Схему это не меняет и менять не должно: ни одна `*_i18n`-колонка не
-- ограничивает набор ключей (jsonb без CHECK — осознанно, см. 0101), а
-- `menu_items.language` — это varchar без CHECK. Набор языков живёт ровно в
-- одном месте, `domain.SupportedLocales`, и расширяется выкаткой кода, а не
-- миграцией.
--
-- Единственное, что здесь всё-таки ЛЖЁТ после расширения набора, — комментарий
-- к колонке из миграции 0100: он перечисляет `ru/kk/en` как исчерпывающий
-- список. Комментарий читают глазами в psql, поэтому он чинится тем же
-- способом, каким был написан.
--
-- Данные не трогаются. На таблице с живыми строками COMMENT не берёт тяжёлых
-- блокировок и не переписывает ни одной страницы.

COMMENT ON COLUMN menu_items.language IS
  'Ярлык языка ТЕКСТА строки (ru/kk/en/ko/zh, NULL = базовая русская строка). НЕ фильтр чтения: гостевая выдача отдаёт базовые строки заведения и локализует их из *_i18n. Коды нормализуются на записи (domain.NormalizeLocale), исторический ''kz'' переведён в ''kk'' миграцией 0100. Набор языков задаётся кодом (domain.SupportedLocales), а не ограничением БД.';

