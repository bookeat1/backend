-- «Выбрали для вас» — подборка заведений на главной, которую СОБИРАЕТ РУКАМИ
-- платформа.
--
-- ЧТО БЫЛО. Никакой подборки на сервере не существовало. Ленту собирал КЛИЕНТ:
-- мобильное приложение звало GET /restaurants?is_popular=true&per_page=20 и
-- брало первые 8 (packages/api/src/http-repository.ts, getPopularRestaurants +
-- RECOMMENDED_LIMIT = 8). То есть состав ленты был следствием флага is_popular
-- и колонки display_order, и задать «вот эти пять, вот в таком порядке» было
-- нельзя: чтобы поднять заведение в ленте, приходилось двигать его во ВСЁМ
-- каталоге, потому что порядок там один и тот же.
--
-- ЧТО ДЕЛАЕТ ЭТА МИГРАЦИЯ. Заводит одну таблицу: город → упорядоченный список
-- заведений. Пустой список для города = «ничего не выбрано руками», и лента
-- считается ровно как раньше (см. usecase/homepicks). Ни одна существующая
-- строка не переписывается, ни одна колонка не меняется — до первого сохранения
-- из админки поведение главной побайтно прежнее.
--
-- ПОЧЕМУ ГОРОД — КЛЮЧ, А НЕ ПРИЗНАК. Главная уже городская: /feed требует
-- ?city=, гастропрогулки требуют, афиша фильтруется по городу заведения, а
-- коллекции гастрогида (0061) держат собственную колонку `city`. Общий на всю
-- платформу список показывал бы гостю в Астане алматинские заведения, то есть
-- ровно ту болезнь, от которой лечили остальные блоки. Форма ключа — как у
-- гастрогида: «этот город» либо «все города».
--
-- ПОЧЕМУ city — ПУСТАЯ СТРОКА, А НЕ NULL, ДЛЯ «ВСЕХ ГОРОДОВ». В гастрогиде
-- «везде» — это city IS NULL, и там это ничему не мешает: город не входит ни в
-- один ключ. Здесь входит в оба — в первичный ключ и в уникальность позиции.
-- В Postgres NULL не равен NULL, поэтому с NULL-городом ОБА ограничения молча
-- перестали бы защищать общий список: одно заведение можно было бы вставить в
-- него дважды, и два заведения — на одну позицию. Пустая строка сравнивается
-- как обычное значение, и ограничения работают для общего списка так же, как
-- для городского. Города с пустым названием не бывает, так что значение
-- свободно.
--
-- ПОЧЕМУ ПОЗИЦИЯ, А НЕ ПОРЯДОК ВСТАВКИ. Владелец просил задавать порядок —
-- значит порядок это данные, а не побочный эффект created_at, который нельзя
-- поменять, не удалив и не вставив строку заново.
--
-- НОМЕР. Прод стоит на 87 (0087_menu_top_picks). Заняты незалитыми ветками:
-- 0088 — feat/story-expiry, 0089 — feat/notify-bot-migration. Следующий
-- свободный, не пересекающийся ни с одной живой веткой, — 0090.

SET lock_timeout = '3s';

CREATE TABLE home_picks
(
    -- Ключ подборки: название города ровно в том написании, что лежит в
    -- restaurants.city, либо '' — подборка «для всех городов», которой
    -- пользуются города без своей собственной.
    --
    -- Не внешний ключ на cities (0081) намеренно, и по той же причине, что в
    -- гастрогиде: город заведения хранится в каталоге ВАРХАРОМ, справочник
    -- 0081 — это про написания и синонимы, а не про источник истины для
    -- колонки. Ссылка на него сделала бы невозможным '' и разошлась бы с тем,
    -- по чему реально фильтруется каталог.
    city          varchar     NOT NULL DEFAULT '',
    -- ON DELETE CASCADE: удалённое заведение уносит своё членство с собой, и
    -- читающему запросу не остаётся висячей строки. ВЫКЛЮЧЕНИЕ заведения
    -- (is_active = false) — вещь другая и куда более частая: оно обрабатывается
    -- на ЧТЕНИИ (заведение просто выпадает из ленты гостя), чтобы владелец не
    -- терял свою подборку из-за временной паузы у ресторана.
    restaurant_id uuid        NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    position      integer     NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    -- Одно заведение — не больше одного раза в подборке города. Присутствовать
    -- и в городской, и в общей подборке оно при этом может: это разные ключи и
    -- разные ответы на разные вопросы.
    PRIMARY KEY (city, restaurant_id),
    -- Один слот — одно заведение. Это и есть то, что делает порядок настоящим,
    -- а не рекомендательным. DEFERRABLE INITIALLY DEFERRED — чтобы
    -- перенумерация внутри одной транзакции не падала на промежуточном
    -- состоянии.
    CONSTRAINT home_picks_position_unique
        UNIQUE (city, position) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT home_picks_position_positive CHECK (position > 0)
);

COMMENT ON TABLE home_picks IS
    'Ручная подборка заведений для блока «Выбрали для вас» на главной. '
        'Пустая подборка города = блок собирается автоматически, как до 0090.';
COMMENT ON COLUMN home_picks.city IS
    'Город подборки в написании restaurants.city; '''' = подборка для всех городов.';

-- Обратный вопрос — «в каких подборках это заведение» — нужен при выключении и
-- удалении заведения. Прямой (город → порядок) уже проиндексирован уникальным
-- ограничением выше, второго индекса под него не создаём.
CREATE INDEX idx_home_picks_restaurant ON home_picks (restaurant_id);

