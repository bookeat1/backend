-- «Лучшие позиции» — блюда, которые ВЫБИРАЕТ САМО ЗАВЕДЕНИЕ из раздела меню в
-- админке.
--
-- ЧТО БЫЛО. Никакого серверного признака «популярное блюдо» не существовало.
-- Ленту «Популярное в меню» собирал КЛИЕНТ: мобильное приложение брало
-- GET /restaurants/:id/menu, фильтровало is_available, сортировало по
-- display_order и брало первые 8 (packages/api/src/http-mapping.ts,
-- mapMenuHighlights + MENU_HIGHLIGHT_LIMIT = 8). То есть заведение управляло
-- лентой только косвенно — порядком блюд во всём меню.
--
-- is_featured (0062) — ЭТО ДРУГОЕ. Тот флаг питает СКВОЗНУЮ по заведениям ленту
-- «Выбор шефа» на главном экране, он городской и модерируемый. Переиспользовать
-- его под ленту внутри карточки заведения значило бы связать два независимых
-- решения: «покажите это блюдо всему городу» и «это наша визитная карточка».
--
-- ПОЧЕМУ ПОЗИЦИЯ, А НЕ boolean. Позиция даёт заведению порядок в ленте (первое
-- блюдо в «Лучших позициях» — не случайное) и, главное, превращает верхнюю
-- границу из проверки в приложении («посчитали перед вставкой» — гонка) в
-- ограничение БД: 8 слотов, частичный уникальный индекс, CHECK 1..8. Две
-- одновременные отметки не могут дать девятую позицию.
--
-- ПОЧЕМУ 8. Ровно столько рисует лента сегодня (MENU_HIGHLIGHT_LIMIT = 8).
-- Разрешить больше — значит позволить заведению отметить блюдо, которое гость
-- никогда не увидит, и не сказать ему об этом.
--
-- БЕЗОПАСНОСТЬ НА ЖИВЫХ СТРОКАХ. Колонка NULLable без DEFAULT — правка каталога,
-- существующие строки не переписываются. Все они получают NULL = «заведение
-- ничего не отметило», и лента для них считается ровно как раньше (см. фолбэк в
-- usecase). Поведение не меняется ни у одного заведения, пока кто-то не отметит
-- блюдо руками.
--
-- НОМЕР. Прод стоит на 85. 0086 занят веткой feat/story-action-url
-- (0086_story_action_url.sql, уже применена на общей тестовой БД), поэтому
-- следующий свободный для этой ветки — 0087.

SET lock_timeout = '3s';

ALTER TABLE menu_items
  ADD COLUMN top_pick_position smallint;

-- Верхняя граница живёт в БД, а не только в Go: приложение можно обойти
-- (миграция данных, ручной UPDATE, второй сервис), ограничение — нет.
-- NOT VALID + VALIDATE, а не обычный ADD CONSTRAINT: обычный берёт
-- ACCESS EXCLUSIVE на время полного скана таблицы. Здесь скан заведомо пустой
-- (колонка только что создана, везде NULL), но форма «сначала каталог, потом
-- проверка под SHARE UPDATE EXCLUSIVE» — правильная привычка для таблицы,
-- которая растёт.
ALTER TABLE menu_items
  ADD CONSTRAINT menu_items_top_pick_position_check
  CHECK (top_pick_position IS NULL OR (top_pick_position BETWEEN 1 AND 8)) NOT VALID;

ALTER TABLE menu_items VALIDATE CONSTRAINT menu_items_top_pick_position_check;

-- Один слот — одно блюдо в пределах заведения. Это же ограничение и есть
-- защита от гонки: два параллельных «отметить» вычислят один и тот же
-- свободный слот, но вставится только одно, второе получит 23505 и
-- переспросит свободный слот (см. facade.SetTopPick).
-- Частичный индекс: строки без отметки (99%+ меню) в него не попадают, поэтому
-- он стоит почти ничего и одновременно обслуживает чтение ленты
-- (restaurant_id, top_pick_position ASC).
CREATE UNIQUE INDEX uq_menu_items_top_pick
  ON menu_items (restaurant_id, top_pick_position)
  WHERE top_pick_position IS NOT NULL;

COMMENT ON COLUMN menu_items.top_pick_position IS
  'Позиция блюда в ленте «Лучшие позиции» карточки заведения (1..8), выбирается самим заведением из админки. NULL = не отмечено. Гостю отдаются только отмеченные И is_available блюда: снятое в стоп-лист блюдо сохраняет свой слот, чтобы персоналу не пришлось отмечать его заново после возврата.';

-- +goose Down

DROP INDEX IF EXISTS uq_menu_items_top_pick;
ALTER TABLE menu_items DROP CONSTRAINT IF EXISTS menu_items_top_pick_position_check;
ALTER TABLE menu_items DROP COLUMN IF EXISTS top_pick_position;
