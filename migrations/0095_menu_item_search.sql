-- ПОИСК ЗАВЕДЕНИЙ ПО БЛЮДАМ.
--
-- ЧТО БЫЛО. `GET /api/v1/restaurants/search` искал только по названию и
-- описанию заведения (миграция 0026, функция restaurant_search_text + два GIN
-- индекса). Меню в поиск не входило вообще, поэтому запрос «паста» находил
-- заведение ровно тогда, когда слово «паста» кто-то написал в его описании.
--
-- ЧТО ДЕЛАЕМ. Тот же приём, что и для заведения, но для позиции меню: одна
-- IMMUTABLE функция, собирающая ВСЕ локали названия блюда в один документ, и
-- два GIN-индекса над этим выражением — FTS (точное/стеммированное совпадение,
-- ts_rank) и триграммный (опечатки через <%). Никакой денормализации в
-- restaurants: см. блок «ПОЧЕМУ НЕ МАТЕРИАЛИЗОВАННАЯ КОЛОНКА» ниже.
--
-- ПОЧЕМУ ТОЛЬКО НАЗВАНИЕ, БЕЗ ОПИСАНИЯ БЛЮДА. Описания в меню — это состав и
-- подача («подаётся с пастой и соусом песто»), и они превращают запрос «паста»
-- в половину каталога. Заведение должно находиться по тому, что оно ГОТОВИТ, а
-- не по тому, что упомянуто в составе. Если продукт потом решит иначе — это
-- правка одной функции и REINDEX, а не переделка запроса.
--
-- ПОЧЕМУ ЧАСТИЧНЫЕ ИНДЕКСЫ (WHERE is_available). Блюдо в стоп-листе не должно
-- тянуть заведение в выдачу: гость, пришедший за пастой, которой нет, — это
-- худший вид «нашлось». Признак стоп-листа в этой схеме один — is_available
-- (0003); is_featured (0062) и top_pick_position (0087) — это витрины, а не
-- доступность, и к поиску отношения не имеют. Условие индекса ПОВТОРЕНО в
-- запросе дословно (`m.is_available`), иначе планировщик частичный индекс не
-- возьмёт. Побочная выгода: индекс не хранит недоступные строки.
--
-- ПОЧЕМУ НЕ МАТЕРИАЛИЗОВАННАЯ КОЛОНКА У ЗАВЕДЕНИЯ. Альтернатива —
-- restaurants.menu_search_text, наполняемая триггером по menu_items. Она дала
-- бы один предикат и BitmapOr, как сегодня, но: (1) триггер на каждую строку
-- при заливке меню из legacy-синка пересобирает весь документ заведения, то
-- есть O(n²) на импорте меню в 500 позиций; (2) любой апдейт is_available
-- обязан перестраивать документ, иначе стоп-лист начинает врать — это
-- дрейфующее состояние, которое некому проверять; (3) «какое блюдо совпало»
-- из склеенного документа не достаётся вообще. Живой JOIN этих трёх проблем не
-- имеет и на текущих объёмах (45 заведений, ~2 200 позиций) стоит единицы
-- миллисекунд. Порог, за которым разговор стоит вернуть: сотни заведений —
-- тогда внешний скан по restaurants перестаёт быть бесплатным.
--
-- НОМЕР. На origin/develop последняя миграция 0091 (0088/0089 пропущены,
-- 0090/0091 заняты). 0092–0094 оставлены с запасом под ветку про статьи,
-- которая делается параллельно и тоже принесёт миграцию.

-- БЕЗОПАСНОСТЬ НА ЖИВЫХ СТРОКАХ. Миграция только добавляет: ни одной колонки,
-- ни одной перезаписи строк. CREATE INDEX (без CONCURRENTLY) берёт SHARE и на
-- время построения блокирует ЗАПИСЬ в menu_items — на 2 200 строках это
-- десятки миллисекунд (замерено: вся миграция 22 мс). lock_timeout не даёт
-- встать в очередь за долгой транзакцией и заморозить правку меню.
SET lock_timeout = '3s';

-- +goose StatementBegin
-- COST 1000 — ровно по той же причине, что у restaurant_search_text: функция
-- делает реальную работу (jsonb_each_text + string_agg на вызов), и с
-- дефолтной стоимостью 100 планировщик недооценивает пересчёт на каждой строке
-- и выбирает seq scan вместо GIN-индекса. Это уже стоило один раз 10x
-- (см. комментарий в 0026).
--
-- ORDER BY key в string_agg обязателен: без него порядок склейки ключей jsonb
-- не определён, обещание IMMUTABLE ложно, и индекс может разойтись с
-- пересчётом того же выражения в запросе.
CREATE OR REPLACE FUNCTION menu_item_search_text(
    name text, name_i18n jsonb
) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE COST 1000 AS $$
    SELECT concat_ws(' ',
        name,
        (SELECT string_agg(value, ' ' ORDER BY key)
           FROM jsonb_each_text(COALESCE(name_i18n, '{}'::jsonb)))
    )
$$;
-- +goose StatementEnd

CREATE INDEX idx_menu_items_search_fts ON menu_items
    USING gin (to_tsvector('russian', menu_item_search_text(name, name_i18n)))
    WHERE is_available;

CREATE INDEX idx_menu_items_search_trgm ON menu_items
    USING gin (menu_item_search_text(name, name_i18n) gin_trgm_ops)
    WHERE is_available;

COMMENT ON FUNCTION menu_item_search_text(text, jsonb) IS
  'Поисковый документ позиции меню: название на всех локалях (базовая колонка + все значения name_i18n). Backs idx_menu_items_search_fts / _trgm; ссылаться на выражение в запросе нужно ДОСЛОВНО.';

-- +goose Down

DROP INDEX IF EXISTS idx_menu_items_search_trgm;
DROP INDEX IF EXISTS idx_menu_items_search_fts;
DROP FUNCTION IF EXISTS menu_item_search_text(text, jsonb);
