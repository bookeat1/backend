-- Откат сносит ОЧЕРЕДЬ ОПРОСА, а не бизнес-данные: единственная потеря — ещё
-- не разрешённые тикеты, то есть отложенная возможность узнать про мёртвый
-- токен. Ledger доставок (`notification_deliveries`) и сами токены не задеты,
-- ни один FK на push_tickets не смотрит, поэтому DROP безопасен и на живой
-- таблице. После наката обратно очередь просто наполняется заново из новых
-- отправок.
DROP TABLE push_tickets;
