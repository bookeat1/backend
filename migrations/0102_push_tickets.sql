-- КВИТАНЦИИ EXPO: ТИКЕТ, ПО КОТОРОМУ МОЖНО СПРОСИТЬ «ДОШЛО ЛИ НА САМОМ ДЕЛЕ».
--
-- Expo отвечает на отправку ТИКЕТОМ, а не результатом доставки. `status: ok`
-- значит «приняли в очередь», и только квитанция (`POST /--/api/v2/push/
-- getReceipts` по id тикета) говорит, что случилось у APNs/FCM. Проверено
-- живьём 2026-09-01 на боевых android-токенах: отправка вернула `ok` по всем
-- трём, а квитанции — `DeviceNotRegistered` по двум из трёх.
--
-- До этой таблицы id тикета выбрасывался сразу после разбора ответа, поэтому
-- отложенный `DeviceNotRegistered` не видел НИКТО: гость молча не получал
-- пуш, в логах было чисто, а мёртвый токен навсегда оставался
-- `device_push_tokens.is_active = true` и продолжал попадать в веер отправки.
-- `DeactivateByID` срабатывал только в редком случае, когда Expo сообщал об
-- ошибке уже в ответе на отправку.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА В `notification_deliveries`. Строка
-- ledger'а появляется ТОЛЬКО на успех и означает «этому таргету это событие уже
-- слали» — она про дедупликацию, живёт вечно и её читает горячий путь веера.
-- Тикет живёт сутки (дольше Expo квитанции не хранит), его читает фоновой
-- воркер и после разрешения строка становится мусором. Смешивать вечный ключ
-- дедупликации с суточной очередью опроса — значит навесить на горячий путь
-- индекс, который нужен только воркеру.

CREATE TABLE push_tickets
(
    -- Идентификатор тикета, как его вернул Expo. PRIMARY KEY, потому что
    -- повторная запись того же тикета (ретрай отправки после падения между
    -- сетью и записью) обязана быть ничем, а не вторым опросом.
    ticket_id       text PRIMARY KEY,
    -- Чей это девайс. ON DELETE CASCADE обязателен: `device_push_tokens.user_id`
    -- уже каскадится от `users`, и без каскада здесь удаление аккаунта падало бы
    -- на этом FK. Мёртвый токен при этом НЕ удаляется, а деактивируется, так что
    -- на живом пути каскад не срабатывает никогда.
    device_token_id uuid        NOT NULL REFERENCES device_push_tokens (id) ON DELETE CASCADE,
    -- Событие outbox'а, из которого вырос пуш. Нужно только для разбора
    -- инцидентов («какие брони не доехали»), поэтому БЕЗ внешнего ключа и
    -- nullable: судьба тикета не должна зависеть от того, жива ли строка
    -- outbox'а, — та же причина, по которой 0039 снял FK с
    -- `notification_deliveries`.
    outbox_event_id uuid,
    created_at      timestamptz NOT NULL DEFAULT now(),
    -- NULL = квитанция ещё не получена. Ставится и при полученном ответе, и
    -- принудительно по возрасту: Expo чистит квитанции через 24 часа, и без
    -- этого таблица росла бы вечно, а воркер вечно спрашивал бы про тикеты,
    -- ответа на которые уже не существует.
    resolved_at     timestamptz
);

-- Рабочий запрос воркера ровно один: «неразрешённые, старше N минут, самые
-- старые вперёд». Частичный индекс по этому предикату сжимается по мере
-- разбора очереди и не тащит за собой разрешённые строки.
CREATE INDEX idx_push_tickets_unresolved
    ON push_tickets (created_at) WHERE resolved_at IS NULL;

