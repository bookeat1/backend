-- Сторис получает ВНЕШНЮЮ ССЫЛКУ — то, куда гость попадает по тапу на карточку.
--
-- ЧТО БЫЛО. В 0065 у `restaurant_stories` есть `image_url` — адрес САМОЙ
-- КАРТИНКИ, и больше никаких ссылок. Тап по сторис никуда не вёл: карточка была
-- чисто декоративной. Маркетологи просят обратное — «Забронировать столик на
-- сайте», «Купить абонемент», пост в инстаграме.
--
-- ЧТО ДЕЛАЕТ. Добавляет ОДНУ колонку `action_url` и тот же второй рубеж
-- проверки схемы, что 0085 завёл для `events.action_url`. Форма ограничения
-- скопирована дословно и намеренно: две сущности, у которых внешняя ссылка
-- означает одно и то же, обязаны и проверяться одинаково, иначе «безопасная
-- ссылка» начинает значить разное в соседних таблицах.
--
-- ЧЕГО ЗДЕСЬ НЕТ — и это отличие от событий. У события пара `action_label` +
-- `action_url`: там КНОПКА, а кнопке нужна подпись, поэтому 0085 запрещает
-- ссылку без подписи. У сторис кнопки нет: тап-целью служит вся карточка
-- целиком, подписывать нечего, и вторая колонка была бы обязательным полем без
-- смысла — оператору пришлось бы выдумывать текст, который никто не рисует.
-- Поэтому здесь только ссылка, а ограничение «ссылка без подписи» неприменимо.
-- Понадобится подпись позже — она добавляется отдельной nullable-колонкой, без
-- переписывания этой.
--
-- НОМЕР. Прод на 85, свободный следующий в `migrations/` — 0086.
--
-- БЛОКИРОВКИ. Nullable-колонка без DEFAULT строки не переписывает; CHECK
-- добавляется вместе с самой колонкой, поэтому проверять существующие строки
-- нечего — у всех них `action_url IS NULL`.

SET lock_timeout = '3s';

ALTER TABLE restaurant_stories
    ADD COLUMN action_url text;

-- Второй рубеж. Основная проверка живёт в domain.ValidateExternalActionURL
-- (запрет javascript:/data:, учётных данных в URL, управляющих символов,
-- относительных адресов), а CHECK ловит запись мимо приложения — ручной UPDATE,
-- будущий импорт — и стоит ноль на INSERT.
--
-- Рубежи не совпадают дословно и не должны: CHECK проверяет форму строки, Go
-- разбирает URL целиком. Здесь закрыто то, что дёшево выразить регуляркой и
-- дорого потерять: схема, длина, пробелы, управляющие байты и «@» — учётные
-- данные в адресе.
ALTER TABLE restaurant_stories
    ADD CONSTRAINT restaurant_stories_action_url_scheme
        CHECK (
            action_url IS NULL
            OR (
                action_url ~* '^https?://[^[:space:][:cntrl:]]+$'
                AND length(action_url) <= 2048
                AND position('@' in action_url) = 0
            )
        );

COMMENT ON COLUMN restaurant_stories.action_url IS
    'Внешняя ссылка (http/https), куда уходит гость по тапу на сторис. NULL = '
        'сторис никуда не ведёт. Это НЕ image_url: image_url — адрес самой '
        'картинки.';

-- +goose Down

ALTER TABLE restaurant_stories
    DROP CONSTRAINT IF EXISTS restaurant_stories_action_url_scheme,
    DROP COLUMN IF EXISTS action_url;
