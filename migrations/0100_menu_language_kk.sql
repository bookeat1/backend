-- +goose Up

-- ЕДИНЫЙ КОД КАЗАХСКОГО ЯЗЫКА В МЕНЮ: 'kz' → 'kk'.
--
-- ЧТО БЫЛО. `menu_items.language` заполнялся импортом значениями 'ru' (2186
-- строк), 'kz' (124) и NULL (66). Всё остальное приложение говорит 'kk':
-- `domain.SupportedLocales`, ключи всех карт `*_i18n`, `Accept-Language` из
-- мобильного приложения. Публичная выдача меню фильтровала СТРОКИ по этой
-- колонке, поэтому `GET /restaurants/:id/menu?lang=kk` отдавал пустой список —
-- строк с 'kk' в базе нет ни одной. Живой баг на проде.
--
-- ЧТО ДЕЛАЕМ. Приводим данные к коду, на котором говорит код: одна UPDATE по
-- 124 строкам. Сам выбор строк по языку убран из репозитория в этой же ветке
-- (выдача теперь не зависит от языка запроса, переводы берутся из `*_i18n`), а
-- колонка остаётся ЯРЛЫКОМ строки, а не фильтром чтения.
--
-- ЧЕГО МЫ ЗДЕСЬ НЕ ДЕЛАЕМ. Эти 124 строки — переводные КОПИИ блюд двух
-- заведений (d2f0e053… и bdce796d…), лежащие отдельными строками рядом с
-- русскими оригиналами. Правильным их видом был бы перенос текста в
-- `name_i18n->'kk'` исходной строки и удаление копии, но однозначного
-- сопоставления «копия → оригинал» в данных НЕТ: у копий нет ссылки на
-- оригинал, `display_order` у всех 0, картинок нет, названия на другом языке, а
-- цена совпадает однозначно только у 16 строк из 62. Угадывать сопоставление
-- значит перемешать позиции чужого меню, поэтому строки оставлены как есть, а
-- от дублей в выдаче защищает запрос (см. baseRowsPredicate в
-- infrastructure/postgres/menu/repository.go): гостю отдаются только базовые
-- строки заведения (language NULL или 'ru'). Сопоставление — отдельная задача
-- для человека/переводчика, и после него текст переедет в `*_i18n` обычным
-- UPDATE.
--
-- БЕЗОПАСНОСТЬ НА ЖИВЫХ СТРОКАХ. Меняется одна текстовая колонка у 124 строк,
-- индексов по ней нет, ограничений на неё нет, внешних ключей нет.
-- `updated_at` НАМЕРЕННО не трогаем: по нему сортируется витрина «выбор
-- шефа» (`ORDER BY m.updated_at DESC` в ListFeatured), и «обновление» 124
-- строк переставило бы ленту без единой правки контента.
--
-- НОМЕР. На origin/develop и в репозитории последняя миграция 0099
-- (0099_telegram_staff_links.sql); в открытых PR миграций выше 0088 нет.
SET lock_timeout = '3s';

UPDATE menu_items SET language = 'kk' WHERE lower(language) = 'kz';

COMMENT ON COLUMN menu_items.language IS
  'Ярлык языка ТЕКСТА строки (ru/kk/en, NULL = базовая русская строка). НЕ фильтр чтения: гостевая выдача отдаёт базовые строки заведения и локализует их из *_i18n. Коды нормализуются на записи (domain.NormalizeLocale), исторический ''kz'' переведён в ''kk'' миграцией 0100.';

-- +goose Down

-- Возврат ровно к тому, что было: на момент 0100 в бою НЕ БЫЛО ни одной строки
-- с 'kk' (только 'ru', 'kz', NULL), поэтому обратный UPDATE по 'kk' попадает в
-- те же самые строки. Если после наката приложение успело записать новые строки
-- с 'kk', они тоже станут 'kz' — и это правильный откат: старый код понимает
-- именно 'kz', а 'kk' для него не существует.
UPDATE menu_items SET language = 'kz' WHERE lower(language) = 'kk';

COMMENT ON COLUMN menu_items.language IS NULL;
